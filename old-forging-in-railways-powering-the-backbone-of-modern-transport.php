                        <div class="col-12 col-lg-8">
                            <h3 class="section-title" id="types">Key Forged Components in Indian Railways</h3>

                            <p>Forged components are widely used across rolling stock and track systems, including:</p>

                            <ul>
                                <li>Bogie parts such as frames, brackets, and suspension arms</li>
                                <li>Coupler components that handle tensile and compressive forces between coaches</li>
                                <li>Axle collars and bearing housings</li>
                                <li>Brake system parts exposed to repeated thermal and mechanical stress</li>
                            </ul>

                            <p>These components must comply with strict dimensional and metallurgical standards, often
                                governed
                                by both Indian Railways specifications and international norms.</p>


                        </div>
