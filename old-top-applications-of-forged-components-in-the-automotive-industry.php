                    <p>If the automotive industry had a backbone, it would be made of forged steel. Unlike cast or
                        welded parts that can crack under stress, forged components are born under pressure – literally.
                        They’re heated, hammered, and honed until the metal’s grain structure aligns with the part’s
                        purpose. The result? Components that don’t just survive – they thrive under impact, vibration,
                        and fatigue.</p>


                    <h3 class="section-title" id="heartbeat">Powertrain: The Heartbeat of Performance</h3>
