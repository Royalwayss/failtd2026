                    <h3 class="section-title" id="types">What Heat Treatment Actually Does to Steel</h3>

                    <p>At a metallurgical level, steel is not static. Its internal structure changes with temperature.
                    </p>

                    <p>Heat treatment works by:</p>

                    <ul>
                        <li><strong>Refining grain structure, </strong> making steel stronger and more uniform</li>
                        <li><strong>Relieving internal stresses </strong> created during forging</li>
                        <li><strong>Improving hardness and wear resistance</strong> </li>
                        <li><strong>Transforming microstructure </strong> to suit the application</li>
                    </ul>

                    <p>A simple analogy: heat treatment is like tuning the engine of the metal. The forging gives the
                        shape, but heat treatment determines how well it performs.</p>

                    <h3 class="section-title" id="choose">Normalizing – Setting the Steel’s Internal Structure Right
                    </h3>

                    <p>Normalizing is the foundation stage.</p>

                    <p>The forged component is heated to a specific temperature and cooled in air. This process:</p>

                    <ul>
                        <li>Refines grain size</li>
                        <li>Removes residual stresses</li>
                        <li>Creates a uniform internal structure</li>
                    </ul>

                    <p>Normalizing prepares steel for further heat treatment and ensures consistency before moving to
                        harder, more demanding stages.</p>

                    <h3 class="section-title" id="common">Quenching – Creating High Strength for Demanding Loads</h3>

                    <p>Quenching is where strength is built.</p>

                    <p>After heating, components are cooled rapidly using controlled media. This locks in hardness and
                        improves load-bearing capability. Quenching is commonly applied to parts such as:</p>

                    <ul>
                        <li>Pinions and flanges</li>
                        <li>Steering knuckles and stub axles</li>
                        <li>Steering arms and hydraulic rod ends</li>
                        <li>Lock jaws, kingpins, pivot pins</li>
                    </ul>

                    <p>These are components that exporters supply to demanding global markets, where performance under
                        load is non-negotiable.</p>
