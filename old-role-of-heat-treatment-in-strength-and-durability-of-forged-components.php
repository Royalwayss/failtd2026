                          <h3 class="section-title" id="workflow">Tempering – Balancing Toughness and Ductility</h3>

                    <p>Hardness alone is not enough.</p>

                    <p>Tempering gently reheats quenched steel to restore toughness and ductility. It prevents
                        brittleness and improves fatigue life. Without tempering, hardened parts may crack under
                        real-world conditions.</p>

                    <p>In simple terms, tempering teaches steel how to bend without breaking.</p>
                        </div>
                    </div>

                    

                    <h3 class="section-title" id="modern">SCADA & CQI-9 – Heat Treatment with Total Digital Control</h3>

                    <p>Modern heat treatment is no longer manual or approximate.</p>

                    <p>SCADA-enabled systems monitor temperature, soak time, and cooling rates in real time. When
                        aligned with <strong> CQI-9 standards, </strong> this digital control delivers:</p>

                    <ul>
                        <li>Predictable mechanical properties</li>
                        <li>Batch-to-batch consistency</li>
                        <li>Full process traceability</li>
                    </ul>

                    <p>This level of control is essential for components supplied to global automotive and
                        heavy-equipment OEMs.</p>

                    <h3 class="section-title" id="future">Testing Methods – Hardness, Microstructure & Ultrasonic Checks
                    </h3>

                    <p>Before dispatch, every heat-treated batch is validated through:</p>

                    <ul>
                        <li><strong>Hardness testing </strong> to confirm strength levels</li>
                        <li><strong>Microstructure analysis </strong> to verify grain formation</li>
                        <li><strong>Ultrasonic testing </strong> to detect internal flaws</li>
                    </ul>

                    <p>These checks close the loop between theory and performance.</p>



                    <h3 class="section-title" id="future">How Heat Treatment Strengthens Automotive & Heavy Equipment
                        Parts</h3>

                    <p>From crankshafts and yokes to brake components and steering assemblies, heat treatment means
                        forged parts can survive millions of operating cycles. It is the reason these components
                        continue performing long after others fail.</p>

