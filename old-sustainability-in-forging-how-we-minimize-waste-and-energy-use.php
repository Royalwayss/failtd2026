                    <p>Sustainability today is not a corporate checkbox – it’s an engineering principle. At Forge Auto International, we don’t just forge steel; we forge a cleaner, smarter and more responsible industrial future. Because strength without conscience is obsolete.</p>

                    <h3 class="section-title" id="energy">Energy-Saving Infrastructure: Powering Responsibility</h3>

                    <p>Energy is the soul of forging. But how we source it defines our impact. Our 300-kW rooftop solar array now meets nearly 60% of FMAPL’s energy demand, reducing dependence on grid electricity and cutting over 70 tonnes of CO₂ emissions annually.</p>

                    <p>We’ve also switched to PNG-based furnaces, a cleaner and more efficient alternative to furnace oil, significantly lowering carbon output during the heating process.</p>

                    <p>Every heat treatment cycle is monitored through SCADA-enabled CQI-9–compliant systems, optimizing energy use in real time while maintaining metallurgical precision.</p>

                    <h3 class="section-title" id="material">Material Efficiency: The Art of Doing More with Less</h3>

                    <p>Forging is already one of the most material-efficient processes in manufacturing. Our near-net shape forging technology minimizes machining allowances and reduces material waste by up to 30%, compared to conventional billet machining. This means fewer chips on the shop floor, and more parts per tonne of steel.</p>

                    <p>We also recycle trimming scrap and reintroduce it into the material stream, promoting a truly circular approach to manufacturing.</p>

                    <h3 class="section-title" id="water">Water Conservation: Every Drop Counts</h3>

                    <p>Water is life – and industry must learn to live lighter. Forge Auto’s facilities operate on closed-loop cooling systems, allowing continuous reuse of water during heat treatment and forging.</p>

                    <h3 class="section-title" id="ecofriendly">Eco-Friendly Lubricants: Clean Forging, Cleaner Air</h3>

                    <p>Traditional lubricants in forging release smoke and residue. We’ve transitioned to sustainable, water-based lubricants, cutting down on fumes and maintaining a cleaner, safer workspace for our team, and a smaller carbon footprint for the planet.</p>

                    <h3 class="section-title" id="afforestation">Afforestation & Carbon Offsetting: Forging Green Roots</h3>

                    <p>Beyond the factory floor, we’ve invested in green offsets that breathe life back into the ecosystem.</p>

                    <p>Our Miyawaki Forest, with over 5,000 native trees, offsets nearly 16,000 tonnes of CO₂, which makes it one of Punjab’s pioneering industrial afforestation models. Every leaf stands as a symbol of our belief that industry and ecology can grow together.</p>

                    <h3 class="section-title" id="certified">Certified for a Cleaner Tomorrow</h3>

                    <p>Our sustainability efforts are backed by international and national recognitions:</p>

                    <ul>
                        <li>ISO 14001:2015 for Environmental Management.</li>
                        <li>ZED (Gold) by the Quality Council of India for Green Manufacturing.</li>
                        <li>Carbon Neutral Certification (FY 2024–25) by Terrablu Climate Technologies Pvt. Ltd.</li>
                    </ul>

