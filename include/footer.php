function get_state_city(action) {
    $('.loadingDiv').show();
    var country = $('#country').find(":selected").attr("data-id");
    if (action == 2) {
        var state = $('#state').find(":selected").attr("data-id");
    } else {
        var state = '';
    }
    $.ajax({
        url: "get-state-city.php",
        type: 'POST',
        data: {
            country: country,
            state: state,
            action: action
        },
        success: function(resp) {
            $('.loadingDiv').hide();

            if (action == '1') {
                $("#state").html(resp);
                $("#city").html('');
            }

            if (action == '2') {
                if ($("#city").attr('data-page') == 'popup') {
                    $('#city').select2({
                        dropdownParent: $('#exampleModal')
                    });
                } else {
                    $('#city').select2();
                }

                $("#city").html(resp);
            }



        },
        error: function() {
            $('.loadingDiv').hide();

        }
    });



}
