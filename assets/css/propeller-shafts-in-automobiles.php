                    <p>When you think about what keeps a vehicle in motion, you probably imagine the engine, the transmission, or maybe even the tires. But tucked underneath the chassis, doing its job without fanfare, is the propeller shaft—a crucial component that ensures your car drives smoothly, efficiently, and safely.</p>

                    <p>So, what exactly does a propeller shaft do? And why is it so essential to your vehicle’s performance? Let’s break it down.</p>

                    <h3 class="section-title" id="shaft">What Is a Propeller Shaft?</h3>

                    <p>Also known as a <strong> drive shaft </strong> or <strong> prop shaft, </strong> the propeller shaft is a rotating mechanical component that transmits torque from the engine or transmission to the differential, which then powers the wheels.</p>

                    <p>In <strong> rear-wheel drive (RWD) </strong> or <strong>all-wheel drive (AWD) </strong> vehicles, the propeller shaft is especially critical. It acts as the vital link between front-mounted engines and rear wheels, ensuring that the power generated up front makes its way to the back—seamlessly.</p>

                    <blockquote>
                       “A propeller shaft converts rotational energy into kinetic energy, allowing the wheels to move at the correct speed. It’s not just a connector—it’s a precision-engineered bridge between power and motion.”
                        <br>— Automotive Technology Expert, Autocar India
                    </blockquote>

