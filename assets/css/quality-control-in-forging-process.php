                                <tr>
                                    <td>Spectrometer Analysis</td>
                                    <td>Confirms chemical composition of alloy</td>
                                    <td>Spectrometer</td>
                                </tr>
                                <tr>
                                    <td>PMI (Positive Material Identification)</td>
                                    <td>Prevents material mix-ups</td>
                                    <td>Portable XRF Analyser XL2 100G</td>
                                </tr>
                                <tr>
                                    <td>UT (Ultrasonic Testing)</td>
                                    <td>Detects internal flaws and inclusions</td>
                                    <td>Ultrasonic Machine</td>
                                </tr>
                                <tr>
                                    <td>Mill Test Certificate Check</td>
                                    <td>Verifies supplier authenticity</td>
                                    <td>MTC Validation System</td>
                                </tr>
                            </tbody>
                        </table>
                    </div>

                    <p>Only certified and traceable raw materials move to the forge shop, setting the foundation for consistent quality.</p>

                    <h3 class="section-title" id="step2">Step 2: In-Process Checks</h3>

                    <p>As the metal takes shape, our engineers keep a close watch on every die and dimension.</p>

                    <ul>
                        <li>Die Wear Inspection prevents early tool failure and dimensional drift.</li>
                        <li>Visual and Dimensional Checks detect laps, cracks, or underfills in real time.</li>
                        <li>First Piece Approval (FPA) confirms that every batch begins with perfection.</li>
                    </ul>

                    <p>Real-time process monitoring and data logging help maintain sub-millimetre accuracy, even at high production rates.</p>

                    <h3 class="section-title" id="step3">Step 3: Heat Treatment Monitoring</h3>

                    <p>Heat treatment is where the true properties of steel are refined. At Forge Auto, we use SCADA-enabled furnaces compliant with CQI-9 global standards.</p>

                    <p>This technology monitors temperature uniformity, soak time, and quenching rates digitally. After treatment, each batch undergoes:</p>

                    <ul>
                        <li>Hardness Tests (Rockwell/BHN)</li>
                        <li>Microstructure Evaluation</li>
                        <li>Mechanical Property Validation</li>
                    </ul>

                    <p>Our closed-loop control system achieves consistent metallurgical results, free from overheating or guesswork.</p>

                    <h3 class="section-title" id="step4">Step 4: Final Stage Testing</h3>

                    <p>Before dispatch, every component passes through multi-level testing for flawless performance.</p>

                    <ul>
                        <li>CMM (Coordinate Measuring Machine) for dimensional accuracy</li>
                        <li>Surface Roughness Tester for finish consistency</li>
                        <li>Magnaflux Crack Detection for surface integrity</li>
                        <li>Microstructure and Grain Flow Analysis for internal soundness</li>
                    </ul>

                    <p>Each report is logged, reviewed, and archived digitally for complete traceability and transparency.</p>

                    <h3 class="section-title" id="step5">Step 5: Traceability & Certifications</h3>

                    <p>Every batch is tagged with heat numbers and test reports, allowing any part to be tracked from raw steel to finished forging.</p>

                    <p>Our certifications include:</p>

                    <ul>
                        <li>ISO 9001:2015 : Quality Management</li>
                        <li>IATF 16949:2016 : Automotive Standard</li>
                        <li>ISO 14001:2015 : Environmental Management</li>
                        <li>ISO 45001 : Occupational Health and Safety Management</li>
                        <li>ZED (Gold) : Certified by the Quality Council of India</li>
                    </ul>

                    <h3 class="section-title" id="conclusion">The Final Word: From Quality Control to Quality Engineering</h3>

                    <p>At Forge Auto International, we go beyond inspection. We engineer quality at every stage. Our system is proactive, data-driven, and digitally integrated, so every forged part delivers not only performance but consistency that inspires confidence.</p>

                    <p>In forging, precision isn’t a target. It’s a tradition built into every strike.</p>

