                    <h3 class="section-title" id="quality">Why Quality in Forging Is Non-Negotiable</h3>

                    <p>In the world of metal, strength is only as good as its consistency. One microscopic crack or misaligned grain can compromise an entire system, whether it’s an axle in a tractor or a gear in an automotive.</p>

                    <p>At Forge Auto International, quality control isn’t a department – it’s a mindset. Every component that leaves our floor carries not just a part number but a promise of precision, performance, and reliability.</p>

                    <h3 class="section-title" id="step1">Step 1: Incoming Raw Material Testing</h3>

                    <p>The journey of a flawless forging starts well before the first hammer strike. Every steel bar and billet entering our plant goes through a series of checks:</p>

                    <div class="table-responsive">
                        <table class="blog-table">
                            <tbody>
                                <tr>
                                    <th>Test</th>
                                    <th>Purpose</th>
                                    <th>Equipment</th>
