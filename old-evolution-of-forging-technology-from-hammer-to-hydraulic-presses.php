                    <h3 class="section-title" id="history">Ancient Beginnings – The Era of the Blacksmith</h3>

                    <p>In early civilisations, forging lived in fire-lit workshops. Blacksmiths heated iron in charcoal
                        furnaces, shaping it with hand-held hammers over anvils. These were open-die processes – crude
                        yet effective – used to make weapons, farming tools, hinges and early machine components.</p>

                    <p>Every strike mattered. The metal responded to skill, experience and timing. Grain flow was shaped
                        unknowingly, but effectively. Even in those days, forged parts outperformed cast ones in
                        strength, proving that compression beats pouring when durability matters.</p>
                    <p>Read this comparative article to learn - <a
                            href="https://www.failtd.com/why-forging-is-preferred-over-casting-and-machining.php">Why
                            Forging is Preferred Over Casting and Machining</a></p>

                    <h3 class="section-title" id="types">Industrial Revolution – Rise of Mechanical Hammers & Steam
                        Power</h3>

                    <p>The 18th and 19th centuries changed everything.</p>

                    <p>Steam engines replaced human muscle. Mechanical hammers and early presses introduced consistency,
                        speed and scale. </p>
                    <p>Forging moved from workshops into industrial plants. Output increased. Accuracy improved.
                        Repeatability became possible.</p>
                    <p>This era laid the foundation for forging as an industrial process, supporting railways,
                        shipbuilding and early machinery – the ancestors of today’s precision equipment.</p>
                    <div class="row">
                        <div class="col-12 col-lg-4">
