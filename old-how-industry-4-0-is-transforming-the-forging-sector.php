                    <h3 class="section-title" id="types">Smart Furnaces & SCADA Monitoring</h3>

                    <p>Heating is the heart of forging, and smart furnaces are changing how that heart beats.
                        SCADA-based monitoring systems track temperature, soak time and energy consumption in real time.
                        Deviations are flagged instantly, allowing corrections before defects occur. This level of
                        control stabilizes metallurgical properties, improves repeatability and significantly reduces
                        fuel consumption – making forging both smarter and greener.</p>

                    <h3 class="section-title" id="choose">Automated Forging Lines: Robotics in High-Volume Production
                    </h3>

                    <p>Modern forging lines now feature robotic billet loading, automated die handling and integrated
                        trimming systems. Human intervention shifts from manual handling to supervision and
                        optimization. Backed by in-house CAD, CAM, QForm simulation software and even 3D printing for
                        prototyping, forging plants can validate designs virtually before metal is ever heated. This
                        reduces development cycles and enables faster, safer scale-up.</p>

                    <h3 class="section-title" id="common">CNC-Driven Machining for Tight Tolerances</h3>

                    <p>Forging no longer ends at shaping. CNC machining, guided by digital process planning, delivers
                        the tight tolerances required for complex assemblies – such as axle assemblies used in
                        fifth-wheel coupling systems, defence applications, and heavy-duty mobility solutions.</p>

                    <p>Dimensional accuracy is achieved through online gauging and digital tool monitoring, which
                        continuously measure critical features and provide real-time feedback to the machining process.
                        Smart labelling, in turn, supports traceability and process control – ensuring that each
                        component is correctly identified, tracked and matched to its inspection and machining data.</p>

                    <p>Together, these systems create a closed-loop manufacturing environment. This integrated approach
                        is what differentiates a component supplier from a true wheel assembly manufacturer, capable of
                        delivering fully traceable, system-ready parts with consistent precision.</p>

                    <h3 class="section-title" id="workflow">Data Analytics: Predictive Maintenance in Forging Shops</h3>

                    <p>Every press, furnace and tool generates data. Industry 4.0 converts that data into foresight.
                        Predictive analytics monitor vibration, load patterns and cycle counts to anticipate failures
                        before they occur. Tool life is extended; unplanned downtime is minimized and maintenance shifts
                        from reactive to strategic. The payoff is higher uptime and lower operating costs.</p>

