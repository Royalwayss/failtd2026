          <h3 id="partnership" class="section-title">Partnership Over Procurement</h3>
          <p>The automotive industry operates on precision, reliability and long-term consistency. In such an environment, the role of a forging supplier extends far beyond manufacturing.</p>
          <p>A world-class forging partner, such as Forge Auto International, becomes part of the OEM&rsquo;s value chain &ndash; contributing to performance, quality and innovation.</p>
          <p>As the industry moves toward electrification, lightweighting and sustainability, the companies that will lead are those that integrate&nbsp;<strong>technology, quality systems and environmental responsibility</strong>&nbsp;into every stage of production.</p>
          <p>Because in modern manufacturing,&nbsp;<strong>partnership &ndash; not procurement &ndash; defines success.</strong></p>

